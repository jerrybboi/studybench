revoke all on public.books from authenticated;
grant select, insert, update, delete on public.books to authenticated;
revoke all on public.profiles from anon;
revoke all on public.usage_log from anon;
revoke all on public.payment_log from anon, authenticated;
revoke all on public.profiles from authenticated;
revoke all on public.usage_log from authenticated;
grant select on public.profiles to authenticated;
grant select on public.usage_log to authenticated;

grant select, insert, update, delete on public.books to service_role;
grant select, insert, update, delete on public.profiles to service_role;
grant select, insert, update, delete on public.usage_log to service_role;
grant select, insert, update, delete on public.payment_log to service_role;
revoke all on function public.apply_verified_payment(uuid,text,integer,text,timestamptz) from public, anon, authenticated;
grant execute on function public.apply_verified_payment(uuid,text,integer,text,timestamptz) to service_role;

